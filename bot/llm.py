"""Логика обращения к LLM: решение «вмешаться?» и генерация ответа."""

from __future__ import annotations

import json
import logging
import random
import re
from typing import Iterable

from openai import APIError, AsyncOpenAI

from .memory import HistoryMessage

log = logging.getLogger(__name__)

# Случайное настроение на каждый forced-ответ. Цель — разнообразить
# регистр Юли, чтобы она не штамповала один и тот же тон подряд.
_MOODS = [
    "сонная, но язвительная",
    "токсично-полезная",
    "лениво-ржущая",
    "сухая и едкая",
    "сегодня почти добрая, но не расслабляемся",
    "мемная комментаторша",
    "устала от тупых вопросов",
    "неожиданно рассудительная",
    "коротко и ядовито",
    "в режиме полезной стервы",
]


def _random_mood() -> str:
    return random.choice(_MOODS)


# Строки таблицы прозвищ из персоны (формата «Имя → прозвище, прозвище»).
# Кладём её в user-промпт отдельно, чтобы модель не выдумывала, кого она
# «знает», и брала прозвища ровно из этого списка.
_KNOWN_USER_LINE = re.compile(r"^\s*[A-Za-zА-Яа-яЁё][\w\s/.,-]*[→\-]>\s*.+", re.UNICODE)


def _extract_known_users(persona_text: str) -> str:
    lines: list[str] = []
    for raw in persona_text.splitlines():
        line = raw.strip()
        # Простой эвристический фильтр: строки вида «Имя → прозвище1, прозвище2».
        # Используем именно «→», как в persona.txt. Длину ограничиваем, чтобы
        # случайно не зацепить абзацы с «→» в середине.
        if "→" in line and len(line) <= 200:
            lines.append(line)
    return "\n".join(lines)


# Запреты и приоритет — выносим из персоны в отдельный system-блок, чтобы
# модель видела их как hard rules, а не как часть «характера», от которого
# можно отойти ради колорита.
_FORCED_RULES = (
    "ПРИОРИТЕТ ОТВЕТА:\n"
    "1) Сначала конкретный ответ по сути на текущее сообщение.\n"
    "2) Потом, если уместно — подкол, мем, ирония. Не наоборот.\n"
    "3) Обращаешься лично к автору последнего сообщения по имени/прозвищу из "
    "списка известных участников. К чату собирательно («пацаны», «мужики», "
    "«братаны», «ребят») — только если действительно обращаешься ко всем сразу.\n"
    "\n"
    "ЗАПРЕЩЕНО НАЧИНАТЬ ответ со слов:\n"
    "«Бля», «Блин», «О, бля», «Чё за», «Чувак», «Чел», «Братан», «Пацаны», "
    "«Мужики», «Ну ты». Это первое слово сразу выдаёт нейросетку. Начинай с "
    "самого ответа: цифра / имя / факт / действие / мем. Шаблонный заход типа "
    "«Чё за…» допустим не чаще 1 ответа из 10 и никогда два подряд.\n"
    "\n"
    "ЗАПРЕЩЕНО ПО СМЫСЛУ:\n"
    "— переводить стрелки на чат фразами «а вы что думаете?», «давайте обсуждать», "
    "«чё у вас там?», «пацаны, рассказывайте», «что за тишина?», «где ваши мысли?». "
    "Допустимо только если человек реально ничего не спросил, а кинул пустой "
    "мем/стикер/бессмысленную фразу.\n"
    "— на вопрос «кого знаешь из наших / расскажи про чат / знаешь Х?» отвечать "
    "«кого конкретно?» / «раскрой мысль». Бери 3–5 ребят из блока "
    "«Известные участники» и коротко по каждому. Если данных мало — назови, кого "
    "знаешь, и скажи прямо, что остальных «подписать нормально надо, я не ванга».\n"
    "— на спойлер («чем закончилось», «спойлерни», «как там в конце») отвечать "
    "«все сдохли, всё странно». Нужны 3–4 конкретных факта: имена, события, кто "
    "кого. Не помнишь точно — скажи прямо «деталей не помню», без вымысла.\n"
    "— заканчивать каждый ответ вопросом к чату. Вопрос задавай только когда "
    "реально нужна информация, чтобы ответить.\n"
    "— повторять структуру последних ответов Юли (см. блок «Последние ответы Юли»).\n"
    "— выдумывать факты и людей, которых не знаешь. Если не знаешь — скажи прямо.\n"
    "\n"
    "МАТ:\n"
    "— максимум 1–2 матерных слова на ответ. Если набралось 3+ — переписывай.\n"
    "— «бля» как слово-паразит в каждом ответе — табу.\n"
    "— примерно каждый третий ответ — вообще без мата, чтобы тон не был монотонным.\n"
    "\n"
    "ПРОСЬБА ПОЗВАТЬ ЧЕЛОВЕКА:\n"
    "Если в текущем сообщении есть «позови» / «зови» / «кликни» и @username "
    "(или имя из таблицы прозвищ) — ПЕРВОЕ слово твоего ответа = это @username "
    "или прозвище. Обращаешься к нему, а не к тому, кто попросил позвать. Потом "
    "одной строкой: «тебя <кто> зовёт, заходи / отзовись». Не объясняй, почему "
    "не стоит звать — просто зови.\n"
    "\n"
    "ВАРИАТИВНОСТЬ: на этот ответ выбери один из режимов — короткий ехидный "
    "коммент / полезный ответ с подколом / мемная реакция / сухой вердикт / "
    "уточняющий вопрос с наездом / мини-разбор / троллинг. Не используй один "
    "режим больше двух раз подряд.\n"
    "\n"
    "ОПАСНЫЕ ТЕМЫ (здоровье, алкоголь, наркотики, самоповреждение, насилие, "
    "закон): стебать по форме можно, по сути — отвечай аккуратно, без вредных "
    "советов."
)


_DECISION_INSTRUCTION = (
    "Ты находишься в групповом чате друзей и читаешь последние сообщения. "
    "Реши, стоит ли тебе ответить прямо сейчас. "
    "Вмешивайся ТОЛЬКО если есть что сказать по существу: "
    "ответить на прямой вопрос (даже если не к тебе обращены, но повисло без ответа), "
    "поправить фактическую ошибку, поддержать обсуждение удачной ремаркой или шуткой. "
    "В остальных случаях молчи. "
    "Не комментируй каждое сообщение — это раздражает. "
    "Не повторяйся. Не спрашивай, чем помочь. Не извиняйся."
)


_OUTPUT_FORMAT = (
    'Верни СТРОГО JSON одного из двух видов: '
    '{"speak": false} — если ничего не отвечать, '
    'или {"speak": true, "text": "<твой ответ>"} — если отвечаешь. '
    'Никакого markdown, никаких пояснений вокруг JSON.'
)


def format_history(messages: Iterable[HistoryMessage]) -> str:
    lines: list[str] = []
    for m in messages:
        speaker = "[bot]" if m.is_bot else f"[{m.user_name}]"
        text = m.text.replace("\n", " ").strip()
        if not text:
            continue
        lines.append(f"{speaker}: {text}")
    return "\n".join(lines)


class LLM:
    def __init__(
        self,
        api_key: str,
        base_url: str | None,
        model: str,
        temperature: float,
        max_tokens: int,
    ) -> None:
        self.client = AsyncOpenAI(api_key=api_key, base_url=base_url)
        self.model = model
        self.temperature = temperature
        self.max_tokens = max_tokens

    async def reply(
        self,
        persona_text: str,
        history: list[HistoryMessage],
        forced: bool,
        current_message: str = "",
        bot_replies: list[HistoryMessage] | None = None,
    ) -> str | None:
        """Возвращает текст ответа или None, если бот решил промолчать.

        forced=True — упоминание / reply / личка. Модель получает:
          • system: персона;
          • system: случайное настроение Юли + жёсткие правила (приоритет
            ответа по сути, запреты, варианты регистра, опасные темы);
          • user: контекст чата, последние ответы Юли, известные участники,
            конкретное сообщение для ответа, задача.
          Просим обычный текст без JSON — иначе модель иногда возвращала
          {"speak": false} даже на прямое обращение, и пользователь видел
          тишину.

        forced=False — режим «решить, влезать ли» (используется только при
        обычном кулдауне < бесконечности). JSON нужен, чтобы отличить
        «промолчать» от «ответить вот так».
        """
        history_str = format_history(history) or "(история пуста)"
        bot_replies_str = format_history(bot_replies or []) or "(пока не отвечала)"
        known_users = _extract_known_users(persona_text) or "(нет данных)"

        # Кому именно отвечаем — берём последнего «не-бота» из истории.
        # Подсовываем модели его имя в открытую, чтобы она не сваливалась
        # на собирательные «пацаны»/«мужики».
        last_speaker = ""
        for h in reversed(history):
            if not h.is_bot and h.user_name:
                last_speaker = h.user_name
                break

        if forced:
            mood = _random_mood()
            current_block = current_message.strip() or (
                "(см. последнюю строку чата выше — она и есть текущее сообщение)"
            )
            addressee = last_speaker or "(не определено)"

            system_persona = persona_text.strip()
            system_rules = (
                f"Текущее настроение Юли: {mood}.\n\n"
                f"{_FORCED_RULES}"
            )
            user_prompt = (
                f"Контекст чата (последние сообщения):\n{history_str}\n\n"
                f"Последние ответы Юли (не повторяй их структуру и обороты):\n"
                f"{bot_replies_str}\n\n"
                f"Известные участники (имя → прозвища):\n{known_users}\n\n"
                f"Сообщение, на которое надо ответить (автор: {addressee}):\n"
                f"{current_block}\n\n"
                "Задача: ответь на это сообщение конкретно. Если это вопрос — "
                "дай ответ по сути. Если просьба позвать человека — упомяни "
                "его @username и коротко передай, что зовут. Если данных не "
                "хватает — задай ОДИН конкретный уточняющий вопрос. Никакого "
                "JSON, просто текст ответа, в роли Юли."
            )
            messages = [
                {"role": "system", "content": system_persona},
                {"role": "system", "content": system_rules},
                {"role": "user", "content": user_prompt},
            ]
            response_format = None
        else:
            addressee_line = (
                f"Последнее сообщение написал: {last_speaker}. "
                "Если отвечаешь — обращайся именно к нему по имени или прозвищу, "
                "а не ко всему чату.\n\n"
                if last_speaker
                else ""
            )
            system_prompt = (
                f"{persona_text.strip()}\n\n"
                f"{_DECISION_INSTRUCTION}\n\n"
                f"{_OUTPUT_FORMAT}"
            )
            user_prompt = (
                f"Последние сообщения чата:\n{history_str}\n\n"
                f"{addressee_line}"
                "Твой ответ (JSON):"
            )
            messages = [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ]
            response_format = {"type": "json_object"}

        kwargs: dict = {
            "model": self.model,
            "messages": messages,
            "temperature": self.temperature,
            "max_tokens": self.max_tokens,
            # top_p / penalties — чтобы Юля не штамповала один и тот же
            # лексический хвост и заходы. vsegpt.ru / OpenAI-совместимые
            # эндпоинты эти параметры принимают; для моделей, которые их не
            # поддерживают, провайдер обычно просто молча игнорирует.
            "top_p": 1,
            "frequency_penalty": 0.6,
            "presence_penalty": 0.3,
        }
        if response_format is not None:
            kwargs["response_format"] = response_format

        try:
            resp = await self.client.chat.completions.create(**kwargs)
        except APIError as exc:
            log.warning("Ошибка OpenAI API: %s", exc)
            return None
        except Exception as exc:  # noqa: BLE001 — не хотим уронить бота на любой сбой сети
            log.warning("Не удалось получить ответ от LLM: %s", exc)
            return None

        raw = (resp.choices[0].message.content or "").strip()
        if not raw:
            return None

        if forced:
            # Прямой ответ — без JSON. Снимаем возможные обвязки от модели
            # (markdown-фенсы, лишние кавычки).
            return _strip_wrappers(raw)

        try:
            data = json.loads(raw)
        except json.JSONDecodeError:
            log.warning("LLM вернул не-JSON в режиме решения: %r", raw[:200])
            return None

        if not isinstance(data, dict):
            return None
        if not data.get("speak"):
            return None
        text = data.get("text")
        if not isinstance(text, str):
            return None
        text = text.strip()
        return text or None


def _strip_wrappers(text: str) -> str:
    """Снимает markdown-фенсы и обрамляющие кавычки от модели.

    Без response_format=json_object модель иногда заворачивает ответ в
    ```text ... ``` или в обычные кавычки. Юзеру это в чат летит как есть,
    выглядит ущербно — срезаем.
    """
    t = text.strip()
    if t.startswith("```"):
        # ``` или ```lang в начале, ``` в конце
        t = re.sub(r"^```[a-zA-Z]*\s*\n?", "", t)
        if t.endswith("```"):
            t = t[: -len("```")]
        t = t.strip()
    if len(t) >= 2 and t[0] == t[-1] and t[0] in ('"', "«", "“"):
        # Внешние одинаковые кавычки целиком вокруг ответа — снимаем.
        t = t[1:-1].strip()
    return t
