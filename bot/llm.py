# Строки таблицы прозвищ из персоны (формата «@тег → имя, прозвище, ...»
# или «Имя → прозвище, прозвище»). Кладём её в user-промпт отдельно, чтобы
# модель не выдумывала, кого она «знает», и брала прозвища ровно из этого
# списка, плюс по @тегу могла сопоставить автора текущего сообщения.
_KNOWN_USER_LINE = re.compile(r"^\s*[A-Za-zА-Яа-яЁё@][\w\s/.,-]*[→\-]>\s*.+", re.UNICODE)


# Запрещённые лексические открывалки. Промпт-инструкцию «не начинай ответ
# с „Бля,“» gpt-4o-mini выполняет нестабильно, поэтому подстраховываемся
# жёстким постпроцессингом: режем открывалку у самого начала ответа.
_OPENER_RE = re.compile(
    r"^\s*(?:"
    r"бля|блин|нахуй|нах|"
    r"эй|ну\s+ты|"
    r"о[,\s]+бл[яе]|ой[,\s]+бл[яе]|"
    r"чувак|чел|братан|братишк[аи]|пацаны|мужики|ребят[аы]?"
    r")[,\s!?.…]+",
    re.IGNORECASE | re.UNICODE,
)

# «Чё за хрень,», «Чё за хуйня,» и т.п. — отдельным паттерном.
_CHE_ZA_RE = re.compile(
    r"^\s*чё[,\s]+за\s+\S+[,\s!?.…]+",
    re.IGNORECASE | re.UNICODE,
)

# Паттерн «Имя, бля, ...» — модель часто ставит «бля» сразу после
# обращения. Имя оставляем (это нормальный вокатив), «бля» режем.
_NAME_BLYA_RE = re.compile(
    r"^\s*([А-ЯЁA-Z][А-ЯЁа-яёA-Za-z]+)\s*,\s*бл[яе][,\s!?.…]+",
    re.UNICODE,
)


def _strip_trailing_filler_question(text: str) -> str:
    """Срезает «вопросительный хвост» в конце ответа.

    Юля систематически добавляет в конец «А ты как?», «Чё ещё хочешь?»,
    «Когда уезжаешь?» — это душнит и нарушает её же роль. Промпт-запрет
    модель игнорирует. Эвристика жёсткая, но безопасная:

      • Если в тексте ЕСТЬ хотя бы одно нормальное окончание предложения
        (`.` / `!` / `…`), и ВСЁ, что идёт ПОСЛЕ последнего такого знака,
        содержит `?` — режем этот хвост целиком. То есть оставляем
        содержательный «приговор» и убираем филлерные вопросы.
      • Если весь ответ — одно предложение-вопрос (нет `.` / `!` / `…`
        вовсе), оставляем как есть: лучше плохой вопрос, чем пустой
        ответ.

    Внутрь предложений (например, «Лёха-темщик, конспиролог,
    хочет в Испанию.») не лезем.
    """
    if not text or "?" not in text:
        return text
    s = text.rstrip()
    if not s:
        return text
    last_sentence_end = -1
    for i, ch in enumerate(s):
        if ch in ".!\u2026":
            last_sentence_end = i
    if last_sentence_end < 0:
        return text
    tail = s[last_sentence_end + 1 :]
    if "?" not in tail:
        return text
    return s[: last_sentence_end + 1].rstrip()


_SUMMON_RE = re.compile(
    r"\b(позови|зови|кликни|разбуди|пни|передай|скажи)\b",
    re.IGNORECASE | re.UNICODE,
)
_OPENER_TOKEN_RE = re.compile(
    r"^\s*(?P<at>@?)(?P<name>[A-Za-zА-Яа-яЁё][\w\-]{1,30})\s*[,:\-—]\s*",
    re.UNICODE,
)


def _enforce_addressee(
    text: str,
    author_nick: str | None,
    aliases_map: dict[str, str] | None,
    current_message: str,
) -> str:
    """Подменяет неверного адресата в начале ответа.

    Модель в forced-режиме регулярно открывает ответ именем СУБЪЕКТА досье
    («Лёха, …»), когда автор сообщения — другой человек («Антоха»). Промпт-
    инструкции это не дожимают, поэтому страхуем кодом.

    Логика:
      • Если автор не определён или нет карты псевдонимов — ничего не делаем.
      • Если в текущем сообщении автор явно просит передать что-то третьему
        лицу («позови / зови / кликни / разбуди / пни / передай / скажи») —
        тоже не лезем: это легитимное обращение к Х.
      • Достаём опенер (первое имя/тег до запятой/двоеточия/тире). Если он
        в `aliases_map` известен и его канонический ключ НЕ совпадает с
        каноническим ключом автора — заменяем опенер на `author_nick`.
      • Вокативные сокращения («Антох», «Лёх», «Серёг») в карте не лежат,
        поэтому через эту проверку проходят без изменений — это и значит
        «модель уже обратилась правильно, не лезь».
    """
    if not text or not author_nick or not aliases_map:
        return text
    if _SUMMON_RE.search(current_message or ""):
        return text
    first_line, sep, rest = text.partition("\n")
    m = _OPENER_TOKEN_RE.match(first_line)
    if not m:
        return text
    opener = (m.group("at") or "") + m.group("name")
    opener_key = opener.lower()
    canonical_opener = aliases_map.get(opener_key)
    if canonical_opener is None and opener_key.startswith("@"):
        canonical_opener = aliases_map.get(opener_key.lstrip("@"))
    if canonical_opener is None:
        return text
    author_canonical = aliases_map.get(author_nick.lower())
    if canonical_opener == author_canonical:
        return text
    tail = first_line[m.end() :]
    new_first_line = f"{author_nick}, {tail}" if tail else f"{author_nick},"
    return new_first_line + (sep + rest if sep else "")


def _strip_forbidden_openers(text: str) -> str:
    """Срезает у ответа модели запрещённые открывалки в начале.

    Цикл до 3 итераций — модель иногда штампует несколько паразитов подряд
    («Бля, эй, мужики, ...»). После стрипа делаем первую букву заглавной,
    чтобы ответ не выглядел рубленым.
    """
    if not text:
        return text
    t = text
    for _ in range(3):
        new = _NAME_BLYA_RE.sub(r"\1, ", t, count=1)
        if new != t:
            t = new
            continue
        new = _OPENER_RE.sub("", t, count=1).lstrip()
        if new != t:
            t = new
            continue
        new = _CHE_ZA_RE.sub("", t, count=1).lstrip()
        if new != t:
            t = new
            continue
        break
    t = t.strip()
    if t and t[0].islower():
        t = t[0].upper() + t[1:]
    return t


def _extract_known_users(persona_text: str) -> str:
    """Достаёт из persona.txt строки таблицы прозвищ.

    Берём только строки формата «@tag → имя, прозвище1, прозвище2». Это
    надёжно отрезает лишний шум: «Арифметика → дай число…» из блока
    КОНКРЕТНОСТЬ или «Лёха: …» → из ПРИМЕРОВ ТОНА в общий ответ не
    утекают.
    """
    lines: list[str] = []
    for raw in persona_text.splitlines():
        line = raw.strip()
        if line.startswith("@") and "→" in line and len(line) <= 300:
            lines.append(line)
    return "\n".join(lines)


